"""A CUBE's packs: one sheet of its whole list, 15 cards a pack, singleton by default (story MC-10).

    python tools/build_cube_boosters.py lsv      # -> MagicCore/Sets/LSV.boosters.json

The format is the booster file every set has (Boosters.cs reads it), so a cube needs no collation code: one pack
variant drawing 15 from the sheet "cube", every card once in the sheet, and "singleton": true — the packs of one
deal (a sealed pool, a draft's 24) never repeat a card. Re-run after the cube's list changes (import_scryfall_set.py).
"""

import json
import sys
from pathlib import Path

SETS = Path(__file__).resolve().parent.parent / "MagicCore" / "Sets"
PACK_SIZE = 15  # a cube pack (LSV's own cube drafts 15)


def main():
    code = sys.argv[1].upper()
    names = sorted({c["name"] for c in json.loads((SETS / f"{code}.json").read_text(encoding="utf-8"))})
    out = {
        "source": f"GENERATED by tools/build_cube_boosters.py {code.lower()} from {code}.json - a cube: every card once, "
        f"{PACK_SIZE} a pack, singleton across a deal; never hand-edit",
        "boosters": [{"weight": 1, "contents": {"cube": PACK_SIZE}}],
        "sheets": {"cube": {"fixed": False, "cards": {n: 1 for n in names}}},
        "singleton": True,
    }
    path = SETS / f"{code}.boosters.json"
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"{path}: {len(names)} cards, {PACK_SIZE} a pack")


if __name__ == "__main__":
    main()
