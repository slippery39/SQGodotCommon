"""Import a set's play-booster collation from MTGJSON into MagicCore/Sets/<CODE>.boosters.json.

    python tools/import_mtgjson_boosters.py fra

MTGJSON models a booster as weighted pack variants, each naming how many cards it takes from each
sheet; a sheet is weighted cards (story LIM-1). Kept as-is except that cards are named, not uuids:
the borderless and other treatments are the same card to the rules, so a card's printings in one
sheet add their weights, and two sheets that become identical (pairX / pairXBorderless) merge, with
the pack variants that then match. Cards from another set (FRA's Special Guests, SPG) are named
from that set's file.
"""

import gzip
import json
import sys
import urllib.request
from pathlib import Path


def fetch(code):
    url = f"https://mtgjson.com/api/v5/{code.upper()}.json.gz"
    req = urllib.request.Request(url, headers={"User-Agent": "SQGodotCardGame/1.0 (personal project)"})
    with urllib.request.urlopen(req) as r:
        return json.loads(gzip.decompress(r.read()))["data"]


def main():
    code = sys.argv[1].upper()
    data = fetch(code)
    play = data["booster"]["play"]
    names = {c["uuid"]: c["name"] for c in data["cards"]}
    for other in ["SPG"]:  # Special Guests ride in this set's packs
        names |= {c["uuid"]: c["name"] for c in fetch(other)["cards"]}

    sheets, alias = {}, {}
    # shortest name first, so a merge keeps pairX and drops pairXBorderless, whatever MTGJSON's order
    for name, sheet in sorted(play["sheets"].items(), key=lambda s: (len(s[0]), s[0])):
        cards = {}
        for uuid, weight in sheet["cards"].items():
            cards[names[uuid]] = cards.get(names[uuid], 0) + weight
        out = {k: sheet[k] for k in ("foil", "fixed", "balanceColors", "allowDuplicates") if sheet.get(k)}
        out["cards"] = dict(sorted(cards.items()))
        same = next((n for n, s in sheets.items() if s == out), None)
        if same:
            alias[name] = same
        else:
            sheets[name] = out

    boosters = {}
    for b in play["boosters"]:
        contents = {}
        for sheet, count in b["contents"].items():
            contents[alias.get(sheet, sheet)] = contents.get(alias.get(sheet, sheet), 0) + count
        key = json.dumps(contents, sort_keys=True)
        boosters[key] = boosters.get(key, 0) + b["weight"]

    out = {
        "source": f"MTGJSON {code}.json data.booster.play (set released {data.get('releaseDate')}) — "
                  "GENERATED by tools/import_mtgjson_boosters.py, never hand-edit",
        "boosters": [{"weight": w, "contents": json.loads(k)} for k, w in boosters.items()],
        "sheets": sheets,
    }
    path = Path(__file__).resolve().parent.parent / "MagicCore" / "Sets" / f"{code}.boosters.json"
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(out['boosters'])} pack variants, {len(sheets)} sheets ({len(alias)} merged) -> {path}")


if __name__ == "__main__":
    main()
