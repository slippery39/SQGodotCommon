"""Compute a set's 17lands card ratings from the PUBLIC datasets into MagicCore/Sets/<CODE>.17lands.json.

    python tools/import_17lands.py fra

17lands permits outside use only of its public datasets (17lands.com/public_datasets,
/usage_guidelines) — never the site's own API, which says "This data is only for use on
17Lands.com". The old card_ratings/data endpoint also serves a frozen snapshot (it ignored every date
range and showed EOE with zero games, 2026-10-20). So this downloads the per-game files and computes
each card's games-in-hand win rate (GIH WR: won, among the games the card was in the opening hand or
drawn — what the site calls GIH WR) and its game count, for Sealed and for Premier Draft (story LIM-1).
Names are mapped onto MagicCore's: 17lands names a prepare card by its front face.
"""

import csv
import datetime
import gzip
import io
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "https://17lands-public.s3.amazonaws.com/analysis_data/game_data/game_data_public.{code}.{fmt}.csv.gz"
FORMATS = {"sealed": "Sealed", "premier": "PremierDraft"}


def gih(code, fmt):
    """card -> [games in hand, wins], and the file's Last-Modified."""
    req = urllib.request.Request(URL.format(code=code, fmt=fmt),
                                 headers={"User-Agent": "SQGodotCardGame/1.0 (personal project)"})
    with urllib.request.urlopen(req) as r:  # streamed: a big set's file never sits in memory whole
        rows = csv.reader(io.TextIOWrapper(gzip.GzipFile(fileobj=r), encoding="utf-8", newline=""))
        header = next(rows)
        won = header.index("won")
        cols = [(c[len("opening_hand_"):], i, header.index("drawn_" + c[len("opening_hand_"):]))
                for i, c in enumerate(header) if c.startswith("opening_hand_")]
        counts = {card: [0, 0] for card, _, _ in cols}
        for row in rows:
            w = row[won] == "True"
            for card, hand, drawn in cols:
                if row[hand] != "0" or row[drawn] != "0":
                    counts[card][0] += 1
                    counts[card][1] += w
        return counts, r.headers.get("Last-Modified")


def main():
    code = sys.argv[1].upper()
    ours = [c["name"] for c in json.loads((ROOT / "MagicCore" / "Sets" / f"{code}.json").read_text(encoding="utf-8"))]
    boosters = ROOT / "MagicCore" / "Sets" / f"{code}.boosters.json"
    if boosters.exists():  # the Special Guests ride in the packs and have ratings too
        sheets = json.loads(boosters.read_text(encoding="utf-8"))["sheets"].values()
        ours += sorted({n for s in sheets for n in s["cards"]} - set(ours))
    by_front = {n.split(" // ")[0]: n for n in ours} | {n: n for n in ours}

    cards, files = {}, []
    for key, fmt in FORMATS.items():
        counts, modified = gih(code, fmt)
        files.append(f"{fmt} ({modified})")
        unknown = [c for c in counts if c not in by_front]
        if unknown:
            sys.exit(f"17lands names not in {code}.json: {unknown}")
        for card, (games, wins) in counts.items():
            cards.setdefault(by_front[card], {})[key] = {
                "gih_wr": round(wins / games, 4) if games else None, "gih_games": games}

    out = {
        "source": f"17lands.com public datasets (CC BY 4.0, by 17Lands), game_data {code}: {', '.join(files)}; computed "
                  f"{datetime.date.today()} — GENERATED by tools/import_17lands.py, never hand-edit",
        "cards": dict(sorted(cards.items())),
    }
    path = ROOT / "MagicCore" / "Sets" / f"{code}.17lands.json"
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(cards)} cards -> {path}")


if __name__ == "__main__":
    main()
